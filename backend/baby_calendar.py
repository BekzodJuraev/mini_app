def generate_child_calendar_events(profile, birth_date: date):
    """
    Генерирует календарь прививок и осмотров для ребенка на основе даты рождения.
    Согласно ТЗ: если ребенок уже старше каких-то этапов, предыдущие не отображаются
    (фильтруем события, дата которых >= даты создания/сегодняшнего дня, либо создаем все от сегодня).
    """
    # Если события уже сгенерированы для этого профиля — не дублируем
    if ChildCalendarEvent.objects.filter(profile=profile).exists():
        return

    today = date.today()
    events_to_create = []

    for months, extra_days, event_type, title, description in SCHEDULE_TEMPLATE:
        # Формула со скриншота: Дата рождения + возраст (месяцы) + дни
        target_date = birth_date + relativedelta(months=months) + timedelta(days=extra_days)

        # По ТЗ: "если ребенок уже старше, то предыдущие не отображаются"
        if target_date >= today:
            events_to_create.append(
                ChildCalendarEvent(
                    profile=profile,
                    event_type=event_type,
                    title=title,
                    description=description,
                    scheduled_date=target_date,
                )
            )

    if events_to_create:
        ChildCalendarEvent.objects.bulk_create(events_to_create)